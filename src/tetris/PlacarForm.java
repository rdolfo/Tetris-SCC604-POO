    private void iniTableSorter(){
        sorter = new TableRowSorter<>(tb);
        tablePlacar.setRowSorter(sorter);
        
        ArrayList<SortKey> keys = new ArrayList<>();
        keys.add(new SortKey(1, SortOrder.DESCENDING)); // Ordena pela coluna
        
        sorter.setSortKeys(keys);
    }
    
